#!/usr/bin/env node
/**
 * Regenerates every derived description of the component library.
 *
 * The code is the ONLY source of truth for what components exist and what props
 * they take. Everything this script writes is a projection of it, and is
 * regenerated rather than edited:
 *
 *   design-system/manifest.json          full machine-readable registry (tooling, prompts)
 *   docs/COMPONENT_CONTRACT.md           the tables between GENERATED markers
 *
 * Human-facing per-tier indexes are colocated in src/components/<tier>/CLAUDE.md and
 * are produced by build-context.mjs, so they auto-load when you work in that tier.
 *
 * The one hand-maintained input is design-system/contract.json — the prop
 * vocabulary is a POLICY decision and is not derivable from code. It is written
 * once there and projected everywhere else.
 *
 *   node build-manifest.mjs              write
 *   node build-manifest.mjs --check      verify committed output matches source; write nothing
 *
 * --check is the CI drift gate. It never mutates the tree, so it cannot "fix"
 * what it is checking.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import prettier from 'prettier';
import { extractComponents, TIERS } from './lib/extract.mjs';

/**
 * Generated output is formatted with the repo's own Prettier config.
 *
 * Without this, `prettier --write` and the generator produce different bytes for
 * the same content, so the drift gate fires forever on files nobody touched. A
 * gate that cries wolf gets disabled, which would cost us the whole guarantee.
 * Formatting here — rather than adding these paths to .prettierignore — keeps the
 * files consistent with the rest of the repo AND keeps the gate stable.
 */
async function format(content, filepath) {
  const config = await prettier.resolveConfig(filepath);
  return prettier.format(content, { ...config, filepath });
}

const ROOT = resolve(import.meta.dirname, '../..');
const CHECK = process.argv.includes('--check');

const contract = JSON.parse(await readFile(join(ROOT, 'design-system/contract.json'), 'utf8'));
// Strip the file's own metadata — it documents contract.json, not the contract.
delete contract.$schema;
delete contract.note;

const components = extractComponents(ROOT);

// ---------------------------------------------------------------------------
// Projections
// ---------------------------------------------------------------------------

function renderManifestJson() {
  return (
    JSON.stringify(
      {
        $schema: './manifest.schema.json',
        version: 1,
        note: 'GENERATED by `pnpm ds:manifest` from source. Do not edit. The contract block is projected from design-system/contract.json.',
        contract,
        components,
      },
      null,
      2,
    ) + '\n'
  );
}

/** Rewrite only the region between GENERATED markers; prose around it is human-owned. */
function renderContractTables() {
  const reserved = Object.entries(contract.reservedProps).map(
    ([name, v]) =>
      `| \`${name}\` | \`${v.type}\` | ${v.meaning}${v.default ? ` (default \`${v.default}\`)` : ''} |`,
  );
  const notes = Object.entries(contract.bannedPropNotes ?? {}).map(
    ([name, why]) => `- \`${name}\` — ${why}`,
  );

  return [
    `### Reserved prop names`,
    ``,
    `| Prop | Type | Meaning |`,
    `|---|---|---|`,
    ...reserved,
    ``,
    `### Banned names — rejected by \`pnpm ds:check\``,
    ``,
    contract.bannedPropNames.map((n) => `\`${n}\``).join(' · '),
    ``,
    ...(notes.length ? [`**Exceptions:**`, ``, ...notes, ``] : []),
    `### Boolean prefixes`,
    ``,
    contract.booleanPrefixes.map((p) => `\`${p}\``).join(' · '),
    ``,
    `### Required files per component`,
    ``,
    contract.requiredFiles.map((f) => `\`${f}\``).join(' · '),
    ``,
  ].join('\n');
}

const START =
  '<!-- GENERATED:contract — do not edit below. Edit design-system/contract.json, then run `pnpm ds:manifest`. -->';
const END = '<!-- /GENERATED:contract -->';

async function projectContractIntoDoc() {
  const path = join(ROOT, 'docs/COMPONENT_CONTRACT.md');
  const current = await readFile(path, 'utf8');
  const body = `${START}\n\n${renderContractTables()}\n${END}`;

  if (current.includes(START) && current.includes(END)) {
    const before = current.slice(0, current.indexOf(START));
    const after = current.slice(current.indexOf(END) + END.length);
    return { path, content: `${before}${body}${after}` };
  }
  return { path, content: current, skipped: true };
}

// ---------------------------------------------------------------------------
// Write or check
// ---------------------------------------------------------------------------

const outputs = [
  { path: join(ROOT, 'design-system/manifest.json'), content: renderManifestJson() },
  await projectContractIntoDoc(),
];

for (const out of outputs) {
  if (!out.skipped) out.content = await format(out.content, out.path);
}

if (CHECK) {
  const drifted = [];
  for (const out of outputs) {
    if (out.skipped) continue;
    let committed = null;
    try {
      committed = await readFile(out.path, 'utf8');
    } catch {
      drifted.push({ path: out.path, reason: 'missing — never generated' });
      continue;
    }
    if (committed !== out.content) {
      drifted.push({ path: out.path, reason: 'out of date with the source it is generated from' });
    }
  }

  if (drifted.length) {
    console.error('\nGenerated files have drifted from the code:\n');
    for (const d of drifted) console.error(`  ${d.path.replace(ROOT + '/', '')}\n    ${d.reason}`);
    console.error('\nFix: run `pnpm ds:manifest` and commit the result.');
    console.error('(This check writes nothing, so it cannot mask the drift it found.)\n');
    process.exit(1);
  }
  console.log(
    `ds:manifest --check passed — ${components.length} components, ${outputs.length - 1} generated files current`,
  );
  process.exit(0);
}

for (const out of outputs) {
  if (out.skipped) {
    console.warn(
      `  warn  ${out.path.replace(ROOT + '/', '')}: GENERATED markers not found, left untouched`,
    );
    continue;
  }
  await writeFile(out.path, out.content);
}

const byTier = TIERS.map((t) => `${components.filter((c) => c.tier === t).length} ${t}`).join(', ');
const propCount = components.reduce((n, c) => n + c.props.length, 0);
console.log(
  `manifest: ${components.length} components (${byTier}), ${propCount} props, ${outputs.length} files written`,
);
